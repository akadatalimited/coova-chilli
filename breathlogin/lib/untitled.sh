#!/bin/bash

# Function to convert CIDR to subnet mask
# Function to convert CIDR to subnet mask
cidr_to_subnet() {
  local cidr=$1
  local mask=""
  local i
  local bits=$(( 32 - cidr ))
  
  for i in $(seq 1 4); do
    if [ $bits -ge 8 ]; then
      mask="$mask$(printf "%d" 255)"
      bits=$((bits - 8))
    else
      mask="$mask$(printf "%d" $(( 256 - (2**(8 - bits)) )))"
      bits=0
    fi
    [ $i -lt 4 ] && mask="$mask."
  done
  echo $mask
}

# Function to calculate the base network (network prefix) from the subnet
cidr_to_network_prefix() {
  local ip=$1
  local cidr=$2
  local net_parts=(${ip//./ })
  local mask=$(cidr_to_subnet $cidr)
  local mask_parts=(${mask//./ })

  # Apply the subnet mask to the network IP to calculate the network address
  for i in {0..3}; do
    net_parts[$i]=$((net_parts[$i] & mask_parts[$i]))
  done

  echo "${net_parts[0]}.${net_parts[1]}.${net_parts[2]}.${net_parts[3]}"
}

# Calculate subnet mask from CIDR and get base network (network prefix)
subnet_mask=$(cidr_to_subnet ${subnet#*/})
network_prefix=$(cidr_to_network_prefix $ip ${subnet#*/})
echo $subnet_mask
echo $network_prefix
#exit 0; 

# Generate client entries with correct dynamic IP calculation
for i in $(seq $range_start $range_end); do
  client_ip="$network_prefix.$i"  # Use the calculated network prefix and client range
  client_name="client-$i.$location.$domain"
  echo "address=/$client_name/$client_ip" >> $config_file
done


# Display help message if no arguments are provided
if [ $# -eq 0 ]; then
echo "Usage: ./generate_dnsmasq_config.sh [OPTIONS]"
echo ""
echo "Options:"
echo "--interface   <interface>      Specify the network interface (e.g., wlan0)"
echo "--host        <hostname>       Specify the base hostname (e.g., hotspot)"
echo "--loc         <location>       Specify the location name (e.g., milford)"
echo "--range       <start> <end>    Specify the DHCP range (e.g., 100 200)"
echo "--client      <client host>    Specify the client name (e.g., client)"
echo "--domain      <domain>         Specify the domain name (e.g., breathtechnology.co.uk)"
echo "--dhcp        <yes/no>         Enable or disable DHCP (default: yes)"
echo "--dns         <dns_ip>        Specify DNS servers (e.g., 1.1.1.1)"
echo ""
echo "Example:"
echo "./generate_dnsmasq_config.sh --interface wlan0 --host hotspot --loc milford --range 100 200 --client client --domain breathtechnology.co.uk --dhcpyes --dns 1.1.1.1 --dns 8.8.8.8"
echo "./generate_dnsmasq_config.sh --interface tun0 --host hotspot --loc milford --client client --dhcp no"
exit 0
fi

# Initialize variables with default values
interface=""
host="router"
location="loc"
range_start="2"
range_end="254"
domain="breathtechnology.co.uk"
dhcp="yes"  # Default to enabling DHCP
dns1="1.1.1.1"  # Default DNS
dns2="8.8.8.8"  # Default DNS

# Function to get IP, CIDR, and Gateway from the interface
get_subnet() {
subnet=$(cat /etc/network/interfaces  | grep -A 4 $interface  | grep address | cut -d '.' -f1-3 | cut -d' ' -f6)
echo $subnet
}
get_netmask() {
netmask=$(cat /etc/network/interfaces  | grep -A 4 wlan0  | grep netmask | cut -d' ' -f6)
echo $netmask
}
# Function to parse arguments
while [[ $# -gt 0 ]]
do
key="$1"

case $key in
--interface)
interface="$2"
shift
shift
;;
--host)
host="$2"
shift
shift
;;
--loc)
location="$2"
shift
shift
;;
--range)
range_start="$2"
range_end="$3"
shift
shift
shift
;;
--client)
client="$2"
shift
shift
shift
;;
--domain)
domain="$2"
shift
shift
;;
--dhcp)
dhcp="$2"
shift
shift
;;
--dns)
if [ -z "$dns1" ]; then
dns1="$2"
else
dns2="$2"
fi
shift
shift
;;
*)
echo "Unknown option: $key"
shift
;;
esac
done

# Validate required parameters
if [ -z "$interface" ] || [ -z "$host" ] || [ -z "$location" ] || [ -z "$range_start" ] || [ -z "$range_end" ] || [ -z "$domain" ]; then
echo "Error: Missing required parameters."
exit 1
fi

# Get details for the given interface if parameters are missing
if [ -z "$range_start" ] || [ -z "$range_end" ] || [ -z "$subnet" ] || [ -z "$router" ]; then
read -r ip cidr gateway <<< $(get_interface_details $interface)

# Calculate subnet mask based on CIDR
subnet_mask=$(get_netmask)

# Set missing parameters based on the interface details
if [ -z "$router" ]; then
router="$gateway"
fi
if [ -z "$subnet" ]; then
subnet="$ip/$cidr"
fi
fi

# Start creating the config file
config_file="/etc/dnsmasq.conf.d/${location}.conf"

# Header for the config file
echo "# Generated by generate_dnsmasq_config.sh" > $config_file
echo "interface=$interface" >> $config_file

# DHCP related options
if [ "$dhcp" == "true" ]; then
echo "dhcp-range=$range_start,$range_end,$subnet_mask,12h" >> $config_file
echo "dhcp-option=3,$router" >> $config_file
echo "dhcp-option=6,$dns1,$dns2" >> $config_file
echo "dhcp-option=15,$location.$domain" >> $config_file
fi

# Add static entries
echo "address=/$host.$location.$domain/$router" >> $config_file

# Generate client entries
# Dynamically calculate the network prefix from the subnet
IFS='.' read -r -a ip_parts <<< "$ip"
network_prefix="${ip_parts[0]}.${ip_parts[1]}.${ip_parts[2]}"

for i in $(seq $range_start $range_end); do
client_ip="$network_prefix.$i"
client_name="$host-$i.$location.$domain"
echo "address=/$client_name/$client_ip" >> $config_file
done

# Optional: Handle other network setups
echo "# End of configuration" >> $config_file

echo "Configuration file created at $config_file"